//OR
let or = '5' || 5; // cuando usamos el operador OR, el resultado es el primer valor verdadero
console.log(typeof or,  or);

//AND
let and = '5' && 5; // cuando usamos el operador AND, el resultado es el primer valor falso o el último valor
console.log(typeof and, and);

//NOT
let not = !'5'; // cuando usamos el operador NOT, el resultado es el valor booleano opuesto 
console.log(typeof not, not);

let not2 = !5; // cuando usamos el operador NOT sin comillas, el resultado es el valor booleano opuesto
console.log(typeof not2, not2);

